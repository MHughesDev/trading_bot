-- The sixteen-gate stack made durable (SPEC §12.3, §12.7; plan 2.14, 2.15, 5.3, 5.5).
--
-- Three things land here, and each one exists because a signal or a gate cannot be
-- computed without it:
--
--   1. `mlops.gate_verdict` — the tenant-scoped, append-only record of every gate
--      decision, carrying the `profile_id` it was judged under. Without this row
--      "gate pass rate by profile" (§16.2) has nothing to read, and a verdict's
--      threshold is only recoverable from whatever code happened to be deployed.
--      The Set J `backtest_gate_verdicts` table stays: it is the five-stage funnel's
--      own record, keyed by experiment and unaware of tenants or profiles.
--
--   2. The `paper_v1` profile (ADR-P2-14). `strict_v1` is untouched — profiles are
--      immutable, so a different purpose is a different profile, never an edit.
--      `paper_v1` authorises paper deployment and *cannot authorise capital*, which
--      is a column here rather than a convention.
--
--   3. `mlops.campaign.platform_seed` (§12.7, ADR-P2-18) — generated by the
--      database, never by a caller, and unreadable by `agent_role`. Gates 11-13 and
--      the ASHA top-3 re-evaluation draw from it, so an agent that could read it
--      could tune against it.

-- ── gate verdicts ─────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS mlops.gate_verdict (
  verdict_id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id           TEXT NOT NULL,
  -- What was judged. At least one of these locates it.
  experiment_id       TEXT,
  trial_id            UUID REFERENCES mlops.trial(trial_id),
  campaign_id         UUID REFERENCES mlops.campaign(campaign_id),
  -- The bar it was judged against. A verdict without its profile is not a verdict:
  -- "passed" means nothing unless you can say passed *what*.
  profile_id          TEXT NOT NULL REFERENCES mlops.gate_profile(profile_id),
  gate_no             INT  NOT NULL CHECK (gate_no BETWEEN 1 AND 16),
  gate_name           TEXT NOT NULL,
  passed              BOOLEAN NOT NULL,
  -- The number that decided it and the bar it cleared or missed, so a later
  -- threshold change can be audited against verdicts already on record.
  statistic           DOUBLE PRECISION,
  threshold           DOUBLE PRECISION,
  detail              TEXT NOT NULL,
  evidence            JSONB NOT NULL DEFAULT '[]'::jsonb,
  -- INV-3: significance is never naked.
  n_eff               DOUBLE PRECISION,
  trial_count_at_eval BIGINT,
  decided_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (experiment_id IS NOT NULL OR trial_id IS NOT NULL),
  CONSTRAINT chk_gate_significance_never_naked CHECK (
    gate_no NOT IN (8, 14) OR (n_eff IS NOT NULL AND trial_count_at_eval IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS idx_gate_verdict_recent
  ON mlops.gate_verdict (tenant_id, profile_id, decided_at DESC);
CREATE INDEX IF NOT EXISTS idx_gate_verdict_subject
  ON mlops.gate_verdict (tenant_id, experiment_id, gate_no);

DROP TRIGGER IF EXISTS trg_gate_verdict_immutable ON mlops.gate_verdict;
CREATE TRIGGER trg_gate_verdict_immutable BEFORE UPDATE OR DELETE ON mlops.gate_verdict
  FOR EACH ROW EXECUTE FUNCTION mlops.refuse_mutation();

ALTER TABLE mlops.gate_verdict ENABLE ROW LEVEL SECURITY;
ALTER TABLE mlops.gate_verdict FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON mlops.gate_verdict;
CREATE POLICY tenant_isolation ON mlops.gate_verdict
  USING (tenant_id = current_setting('app.tenant_id', true))
  WITH CHECK (tenant_id = current_setting('app.tenant_id', true));

GRANT SELECT, INSERT ON mlops.gate_verdict TO app_role;
REVOKE UPDATE, DELETE, TRUNCATE ON mlops.gate_verdict FROM app_role;
-- Agents read verdicts; they hold nothing on the thresholds those verdicts used.
GRANT SELECT ON mlops.gate_verdict TO agent_role;

-- ── per-asset-class gate facts ────────────────────────────────────────────────
--
-- Gate 10's factor battery and Gate 11's crisis windows are *per asset class*, not
-- per-profile scalars (ADR-P2-15, P2-16). They live in their own immutable table
-- rather than inside the thresholds blob, so `strict_v1`'s stored thresholds stay
-- byte-identical to what migration 0043 wrote and every verdict recorded under it
-- still means exactly what it meant.

CREATE TABLE IF NOT EXISTS mlops.gate_profile_asset_class (
  profile_id     TEXT NOT NULL REFERENCES mlops.gate_profile(profile_id),
  asset_class    TEXT NOT NULL,
  -- Gate 10. A regression against factors that do not exist for the asset is not
  -- attribution, so the battery is declared where the asset class is known.
  factor_battery TEXT[] NOT NULL CHECK (cardinality(factor_battery) >= 1),
  -- Gate 11. Facts about the world, not model output, so they belong on the
  -- immutable profile rather than in a regime model's parameters.
  crisis_windows JSONB NOT NULL,
  PRIMARY KEY (profile_id, asset_class)
);
DROP TRIGGER IF EXISTS trg_gate_profile_ac_immutable ON mlops.gate_profile_asset_class;
CREATE TRIGGER trg_gate_profile_ac_immutable
  BEFORE UPDATE OR DELETE ON mlops.gate_profile_asset_class
  FOR EACH ROW EXECUTE FUNCTION mlops.refuse_mutation();

-- ── a profile may or may not authorise capital ────────────────────────────────
-- Adding a column with a constant default does not rewrite rows and does not fire
-- the row-level immutability trigger, so `strict_v1` is not touched by this.
ALTER TABLE mlops.gate_profile
  ADD COLUMN IF NOT EXISTS authorises_capital BOOLEAN NOT NULL DEFAULT TRUE;

