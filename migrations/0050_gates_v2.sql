-- ── the platform-held seed (§12.7) ────────────────────────────────────────────
--
-- Generated by the database, so no code path can supply a predictable one, and
-- re-drawn per campaign because a seed reused across campaigns is a seed that can
-- be learned.
ALTER TABLE mlops.campaign
  ADD COLUMN IF NOT EXISTS platform_seed BIGINT NOT NULL
  DEFAULT (floor(random() * 9007199254740991))::bigint;

-- Agents may read their campaigns — but not this column. A table-level grant cannot
-- be narrowed by a column-level revoke, so the table grant is withdrawn and the
-- columns are granted back one by one. The omission is the mechanism.
REVOKE SELECT ON mlops.campaign FROM agent_role;
GRANT SELECT (campaign_id, slug, tenant_id, hypothesis, objective, benchmark,
              delta_practical, budget, exploration_floor, gates_profile,
              preference_vector, search_space, created_by, created_at)
  ON mlops.campaign TO agent_role;
