//! The SLv2 reference, served a section at a time (S-5.13; AGENT-011 §6, §8.8).
//!
//! # Why a guide that is mostly in this crate
//!
//! A diagnostic carries `see: "guide#exits.units"`. A model that gets one fetches
//! the section it names; a 7B cannot read the whole language to find it. So the
//! guide is cut into sections of at most [`MAX_SECTION_BYTES`] — measured, in a
//! test, not hoped for — and **every `see` anchor the language and the validator
//! can emit resolves to one** (`tests/slv2_guide.rs` scans the sources for them).
//!
//! # What is written and what is generated
//!
//! The grammar sections are prose, written once. Two kinds of section are not:
//!
//! - the **feature reference** is the engine's registry, rendered. A hand-kept
//!   list of 61 families is a second list, and the whole point of AGENT-011 P6 is
//!   that the language is discoverable from the thing that computes it;
//! - the **skeletons** are the compiled skeletons of [`crate::skeleton`], so the
//!   worked example for a family is the text that was proved to compile.
//!
//! They live after one marker line at the end of `docs/slv2-guide.md`, and
//! `tests/slv2_guide.rs` fails when the file differs from [`with_generated`]
//! (regenerate with `SLV2_GUIDE_WRITE=1`).

use crate::skeleton::{self, HypothesisFamily};

/// The guide, as shipped.
pub const GUIDE: &str = include_str!("../docs/slv2-guide.md");

/// The most one section may weigh, heading included: a small tier fetches one
/// at a time (AGENT-011 §8.8).
pub const MAX_SECTION_BYTES: usize = 4096;

/// Everything after this line is generated from the registries.
pub const GENERATED_BEGIN: &str =
    "<!-- generated by strategy_lang::guide; do not edit below this line -->";

/// One section of the guide.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Section {
    /// The first anchor, the one the section is listed under.
    pub anchor: String,
    /// Other anchors that resolve here. `guide#header` and `guide#grammar.header`
    /// are one section: both are spelled in the wild.
    pub aliases: Vec<String>,
    pub title: String,
    /// Heading excluded.
    pub body: String,
}

impl Section {
    /// Whether `anchor` (with or without `guide#`) names this section.
    #[must_use]
    pub fn answers_to(&self, anchor: &str) -> bool {
        let a = anchor.trim().trim_start_matches("guide#");
        self.anchor == a || self.aliases.iter().any(|x| x == a)
    }

    /// The section as served: heading and body.
    #[must_use]
    pub fn text(&self) -> String {
        format!("## {} {{#{}}}\n\n{}", self.title, self.anchor, self.body)
    }

    /// Every anchor this section answers to.
    pub fn anchors(&self) -> impl Iterator<Item = &str> {
        std::iter::once(self.anchor.as_str()).chain(self.aliases.iter().map(String::as_str))
    }
}

/// Cut `text` into sections at `## Title {#anchor [#alias…]}` headings.
#[must_use]
pub fn parse_sections(text: &str) -> Vec<Section> {
    let mut out: Vec<Section> = Vec::new();
    let mut current: Option<(String, Vec<String>, String, Vec<&str>)> = None;
    let flush = |cur: &mut Option<(String, Vec<String>, String, Vec<&str>)>,
                 out: &mut Vec<Section>| {
        if let Some((anchor, aliases, title, lines)) = cur.take() {
            out.push(Section {
                anchor,
                aliases,
                title,
                body: lines.join("\n").trim().to_string(),
            });
        }
    };
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("## ") {
            flush(&mut current, &mut out);
            if let Some((title, anchors)) = rest.rsplit_once(" {") {
                let anchors: Vec<String> = anchors
                    .trim_end_matches('}')
                    .split_whitespace()
                    .filter_map(|a| a.strip_prefix('#'))
                    .map(str::to_string)
                    .collect();
                if let Some((first, more)) = anchors.split_first() {
                    current = Some((
                        first.clone(),
                        more.to_vec(),
                        title.trim().to_string(),
                        Vec::new(),
                    ));
                    continue;
                }
            }
            // A `##` heading with no anchor is not a section a diagnostic can
            // name; its text belongs to nothing and is dropped.
            continue;
        }
        if let Some((_, _, _, lines)) = current.as_mut() {
            lines.push(line);
        }
    }
    flush(&mut current, &mut out);
    out
}

/// The shipped guide's sections.
#[must_use]
pub fn sections() -> Vec<Section> {
    parse_sections(GUIDE)
}

/// The section a `see` anchor names.
#[must_use]
pub fn section(anchor: &str) -> Option<Section> {
    sections().into_iter().find(|s| s.answers_to(anchor))
}

