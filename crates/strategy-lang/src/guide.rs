/// How much one generated reference chunk may weigh, under the section limit
/// with room for the heading.
const CHUNK_BYTES: usize = 3_400;

fn feature_sections() -> String {
    use std::fmt::Write as _;
    let fams: Vec<_> = features::registry::families()
        .iter()
        .filter(|f| f.alias_of.is_none())
        .collect();

    let mut s = String::new();
    s.push_str("## Feature families {#features}\n\n");
    let _ = writeln!(
        s,
        "{} families, read from the engine's registry. A family with parameters is written \
         with them, as in the example column — `rsi` is not a feature, `rsi_14` is. In SLv2 \
         the same feature is `rsi(close, 14)`. `list_features(query=\"…\")` searches them; the \
         reference sections after this one say when to use each.\n",
        fams.len()
    );
    s.push_str("| family | example | warm-up bars |\n|---|---|---|\n");
    for f in &fams {
        let warm = f
            .lookback_bars(&f.example_params())
            .map_or_else(|| "—".to_string(), |w| w.to_string());
        let _ = writeln!(s, "| `{}` | `{}` | {warm} |", f.name, f.example());
    }
    s.push('\n');
    s.push_str(
        "A warm-up is the bars before the feature has a value. `ema_N` needs 5N, so \
         `ema_200` needs 1000: check it against the window (`warmup_exceeds_window`).\n\n",
    );

    // The reference, in chunks that each fit one section.
    let mut chunk = String::new();
    let mut n = 1;
    let mut chunks: Vec<String> = Vec::new();
    for f in &fams {
        let line = format!("- `{}` — {}\n", f.example(), f.use_when);
        if chunk.len() + line.len() > CHUNK_BYTES {
            chunks.push(std::mem::take(&mut chunk));
        }
        chunk.push_str(&line);
    }
    if !chunk.is_empty() {
        chunks.push(chunk);
    }
    let total = chunks.len();
    for c in chunks {
        let _ = write!(
            s,
            "## Feature reference {n} of {total} {{#features.reference.{n}}}\n\n{c}\n"
        );
        n += 1;
    }
    s
}

fn skeleton_sections() -> String {
    use std::fmt::Write as _;
    let mut s = String::new();
    s.push_str("## Skeletons {#skeletons}\n\n");
    s.push_str(
        "A correct first version per hypothesis family, so the first draft is never a syntax \
         lesson. `strategy_skeleton(hypothesis_family)` returns one; it compiles as written, \
         and every parameter is declared so a sweep can vary it. Preview it before changing \
         it.\n\n",
    );
    for f in HypothesisFamily::ALL {
        match skeleton::skeleton(f) {
            Ok(_) => {
                let _ = writeln!(s, "- `{f}` — `{{#skeletons.{f}}}`");
            }
            Err(d) => {
                let _ = writeln!(s, "- `{f}` — not writable yet: {}", d.message);
            }
        }
    }
    s.push('\n');
    for f in HypothesisFamily::ALL {
        let Ok(sk) = skeleton::skeleton(f) else {
            continue;
        };
        let first_para = sk.notes.split("\n\n").next().unwrap_or_default().trim();
        let _ = write!(
            s,
            "## Skeleton: {f} {{#skeletons.{f}}}\n\n```\n{}```\n\n{}\n\n\
             `strategy_skeleton` returns the full notes.\n\n",
            sk.text,
            first_para.replace('\\', "")
        );
    }
    s
}

/// Everything below [`GENERATED_BEGIN`].
#[must_use]
pub fn generated() -> String {
    format!("{}{}", feature_sections(), skeleton_sections())
}

/// `file` with its generated half replaced by the current one.
///
/// Everything before [`GENERATED_BEGIN`] is kept as written; if the marker is
/// absent the file is returned unchanged with the generated half appended.
#[must_use]
pub fn with_generated(file: &str) -> String {
    let head = file
        .find(GENERATED_BEGIN)
        .map_or_else(|| file.trim_end().to_string(), |i| file[..i].trim_end().to_string());
    format!("{head}\n\n{GENERATED_BEGIN}\n\n{}", generated())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn headings_with_several_anchors_answer_to_each() {
        let s = parse_sections("## Header {#grammar.header #header}\n\nbody\n\n## Two {#two}\nx");
        assert_eq!(s.len(), 2);
        assert!(s[0].answers_to("guide#header") && s[0].answers_to("grammar.header"));
        assert!(!s[0].answers_to("two"));
        assert_eq!(s[0].body, "body");
        assert_eq!(s[1].body, "x");
    }

    #[test]
    fn a_heading_without_an_anchor_is_not_a_section() {
        assert!(parse_sections("## Just a title\n\nbody").is_empty());
    }
}
