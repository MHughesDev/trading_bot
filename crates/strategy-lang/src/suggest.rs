/// Above this share of bars, a condition is firing too often to be a rule.
pub const FIRES_TOO_OFTEN: f64 = 0.5;

/// Below this share of the window, a losing regime is not worth a gate.
pub const REGIME_WORTH_GATING: f64 = 0.05;

/// Above this share of closed trades, one exit reason is the exit policy.
pub const EXIT_REASON_DOMINATES: f64 = 0.6;

// ── the thing a suggestion may carry ─────────────────────────────────────────

/// One line of SLv2 — a clause, a predicate, a number. Never a document.
///
/// The constructor refuses a newline, and that single check is what makes "a
/// suggestion never contains a strategy" true by construction: SLv2 puts every
/// clause on its own line (AGENT-011 §3), so no document shorter than two lines
/// exists and no document fits in a `Fragment`.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Fragment(String);

impl Fragment {
    /// `None` when `s` spans more than one line, or is empty.
    #[must_use]
    pub fn new(s: impl Into<String>) -> Option<Self> {
        let s = s.into();
        let trimmed = s.trim();
        if trimmed.is_empty() || s.contains('\n') || s.contains('\r') {
            return None;
        }
        Some(Self(trimmed.to_string()))
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Display for Fragment {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

/// A comparison a gate can be written with.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Cmp {
    Lt,
    Le,
    Gt,
    Ge,
}

impl Cmp {
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Lt => "<",
            Self::Le => "<=",
            Self::Gt => ">",
            Self::Ge => ">=",
        }
    }
}

/// A gate a caller proposes: one feature family, its parameters, a comparison
/// and a bound.
///
/// Checked against the catalogue at construction, so a suggestion cannot carry
/// a feature the engine does not serve or an arity it does not accept —
/// `unknown_feature` and `wrong_arity` are *unreachable* from a suggestion
/// rather than discouraged, the same way [`crate::form`]'s schema makes them
/// unreachable for a constrained decoder.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Predicate {
    family: String,
    params: Vec<u32>,
    op: Cmp,
    bound: Fragment,
    text: Fragment,
}

impl Predicate {
    /// # Errors
    ///
    /// [`Code::UnknownFeature`] for a family the catalogue does not hold,
    /// [`Code::WrongArity`] for the wrong number of parameters,
    /// [`Code::BadFeatureParam`] for one outside the family's declared range,
    /// and [`Code::TypeMismatch`] for a bound that is not a number.
    pub fn new(
        family: impl Into<String>,
        params: Vec<u32>,
        op: Cmp,
        bound: &str,
        cat: &Catalogue,
    ) -> Result<Self, Diagnostic> {
        let family = family.into();
        let Some(f) = cat.family(&family) else {
            let near = cat
                .nearest(&family)
                .map_or_else(String::new, |n| format!("; did you mean `{n}`?"));
            return Err(refuse(
                Code::UnknownFeature,
                format!("no feature family is called `{family}`{near}"),
                "ask `list_features()` for what the engine serves",
            ));
        };
        if f.params.len() != params.len() {
            return Err(refuse(
                Code::WrongArity,
                format!(
                    "`{family}` takes {} parameter(s) and {} were given",
                    f.params.len(),
                    params.len()
                ),
                format!("write `{}`", example_call(&family, &f.params)),
            ));
        }
        for (spec, got) in f.params.iter().zip(&params) {
            let got = i64::from(*got);
            if got < spec.min || got > spec.max {
                return Err(refuse(
                    Code::BadFeatureParam,
                    format!(
                        "`{family}`'s `{}` must be between {} and {}, and {got} is not",
                        spec.name, spec.min, spec.max
                    ),
                    "pick a value inside the family's declared range",
                ));
            }
        }
        if bound.trim().parse::<f64>().is_err() {
            return Err(refuse(
                Code::TypeMismatch,
                format!("`{bound}` is not a number, and a gate compares against one"),
                "write a decimal literal",
            ));
        }
        let bound = Fragment::new(bound).ok_or_else(|| {
            refuse(
                Code::TypeMismatch,
                "a bound must be one line",
                "write a decimal literal",
            )
        })?;
        let args: Vec<String> = std::iter::once("close".to_string())
            .chain(params.iter().map(u32::to_string))
            .collect();
        let text = Fragment::new(format!(
            "{family}({}) {} {bound}",
            args.join(", "),
            op.as_str()
        ))
        .expect("a rendered predicate is one line");
        Ok(Self {
            family,
            params,
            op,
            bound,
            text,
        })
    }

    #[must_use]
    pub fn family(&self) -> &str {
        &self.family
    }

    #[must_use]
    pub fn params(&self) -> &[u32] {
        &self.params
    }

    #[must_use]
    pub const fn op(&self) -> Cmp {
        self.op
    }

    #[must_use]
    pub fn bound(&self) -> &Fragment {
        &self.bound
    }

    /// The predicate as SLv2, ready to be `and`-ed into a condition — by
    /// whoever decides to.
    #[must_use]
    pub fn text(&self) -> &Fragment {
        &self.text
    }
}

fn example_call(family: &str, params: &[crate::catalogue::FamilyParam]) -> String {
    let args: Vec<String> = std::iter::once("close".to_string())
        .chain(params.iter().map(|p| p.min.to_string()))
        .collect();
    format!("{family}({})", args.join(", "))
}

