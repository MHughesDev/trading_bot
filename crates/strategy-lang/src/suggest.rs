//! `suggest_moves`: the next structural moves, each citing the measurement that
//! motivated it (S-5.11; AGENT-011 §4, §10).
//!
//! # It suggests, and it cannot have applied
//!
//! A suggestion that has already been acted on is a rewrite nobody approved,
//! and the difference has to be structural rather than a promise in a doc
//! comment. So:
//!
//! - nothing in this module takes a [`StrategyDefinition`] and returns one;
//! - every piece of text a [`Suggestion`] carries is a [`Fragment`], which
//!   **cannot contain a newline** — and SLv2 puts every clause on its own line,
//!   so the smallest legal document (a header and one clause) has one. A
//!   strategy therefore cannot be smuggled through a suggestion field, and
//!   `a_suggestion_cannot_carry_a_strategy` proves it against the real
//!   skeletons rather than against a made-up string;
//! - the proposal names a clause and an edit, and the caller — or the model —
//!   decides.
//!
//! # Motivated only
//!
//! AGENT-011 §10 settles the open question one way: ship motivated-only, and let
//! the research protocol's Experiment step be where exploration happens. Every
//! [`Suggestion`] carries a typed [`Evidence`], which is a measurement with
//! numbers in it, not a sentence. There is no constructor that takes a reason as
//! a string, so "every suggestion cites the diagnostic that motivated it"
//! (S-5.11's acceptance) is a property of the type rather than a rule a future
//! rule-writer has to remember.
//!
//! # Where a rule fires and the language cannot carry the move
//!
//! Some motivated moves are not writable. FEAT-003 §8.3's answer to "it loses in
//! the high-volatility months" is `change_sizing` to a vol-scaled mode, and the
//! canonical order specification has three size modes, none of which scales by a
//! measured volatility. Emitting the suggestion anyway would spend a model's
//! turn on a document the compiler refuses. So the rule still fires and its
//! result goes into [`Suggestions::withheld`], naming the diagnostic code that
//! would have refused it — refusing by name rather than approximating, which is
//! the same choice `skeleton.rs` makes about `carry`.
//!
//! # Why the vocabulary is not `research::propose::Move` itself
//!
//! It is [`crate::diff::MoveKind`], which is FEAT-004 §6's extension of
//! FEAT-003 §8.3's list, and [`crate::diff::MoveKind::research_kind`] is the
//! join. `strategy-lang` cannot depend on `research`: `research` sits above
//! `backtest` and `ledger`, this crate is a leaf on `domain` and `features`, and
//! the dependency that would make sense is the other one. `Move`'s variants also
//! address *node ids* and carry a free-form `expr: String`, and node ids here
//! are generated by the compiler from clause order — so a move naming one would
//! not survive an inserted clause.

