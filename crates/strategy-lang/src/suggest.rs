    /// The structural half of "it suggests; it never applies". Every string a
    /// suggestion carries is a `Fragment`, and no SLv2 document is one — proved
    /// against the real skeletons rather than against a string written here.
    #[test]
    fn a_suggestion_cannot_carry_a_strategy() {
        for s in crate::skeleton::worked() {
            assert!(
                Fragment::new(s.text).is_none(),
                "the `{}` skeleton fits in a fragment",
                s.family
            );
        }
        assert!(Fragment::new("entry long when rsi(close, 14) < 30").is_some());
        assert!(Fragment::new("a\nb").is_none());
        assert!(Fragment::new("a\r\nb").is_none());
        assert!(Fragment::new("   ").is_none());

        // And over everything the rules really produce.
        let d = def(TWO_CLAUSE);
        let f = Findings {
            blocking: Some(profile(&d, 1000, 0, &[(600, 400), (4, 596)])),
            exit_reasons: vec![ExitReasonShare {
                reason: "stop_loss".into(),
                share: 0.9,
                trades: 20,
            }],
            regimes: vec![RegimeOutcome {
                label: "trending".into(),
                objective: -0.4,
                share_of_window: 0.3,
                gate: Some(
                    Predicate::new("variance_ratio", vec![64, 4], Cmp::Lt, "1", &Catalogue::engine())
                        .expect("a real family"),
                ),
            }],
        };
        let s = suggest_moves(&d, &f).expect("suggestions");
        assert!(s.moves.len() >= 3, "{:#?}", s.moves);
        for m in &s.moves {
            for frag in fragments(&m.proposal) {
                assert!(
                    crate::text_to_definition(frag.as_str()).is_err(),
                    "`{frag}` compiled as a strategy"
                );
            }
        }
    }

    fn fragments(p: &Proposal) -> Vec<Fragment> {
        match p {
            Proposal::MoveThreshold {
                clause, literal, ..
            } => vec![clause.clone(), literal.clone()],
            Proposal::WidenParamRange { param, .. } => vec![param.clone()],
            Proposal::DropClause { clause } => vec![clause.clone()],
            Proposal::AddPredicate { predicate } => {
                vec![predicate.text().clone(), predicate.bound().clone()]
            }
        }
    }

    #[test]
    fn a_predicate_cannot_name_a_feature_the_engine_does_not_serve() {
        let cat = Catalogue::engine();
        let err = Predicate::new("rsi14", vec![], Cmp::Lt, "30", &cat).expect_err("refused");
        assert_eq!(err.code, Code::UnknownFeature);
        assert!(err.fix.is_some());

        let err = Predicate::new("rsi", vec![14, 9], Cmp::Lt, "30", &cat).expect_err("refused");
        assert_eq!(err.code, Code::WrongArity);

        // Read the bound off the registry rather than guessing one: a literal
        // written here would stop being out of range the day the family's range
        // widened, and the test would pass by testing nothing.
        let max = cat.family("rsi").expect("rsi exists").params[0].max;
        let over = u32::try_from(max).expect("a period fits in u32") + 1;
        let err = Predicate::new("rsi", vec![over], Cmp::Lt, "30", &cat).expect_err("refused");
        assert_eq!(err.code, Code::BadFeatureParam);

        let err = Predicate::new("rsi", vec![14], Cmp::Lt, "soon", &cat).expect_err("refused");
        assert_eq!(err.code, Code::TypeMismatch);
    }

