/// Which way a number would have to move.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Direction {
    Raise,
    Lower,
}

impl Direction {
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Raise => "raise",
            Self::Lower => "lower",
        }
    }
}

/// How a strategy did inside one regime, and — if the caller can say — the
/// predicate that identifies it.
///
/// `gate` is optional and its absence is load-bearing. `features::registry`
/// does not label which families measure a regime, so a diagnostic that names
/// `high_vol` and nothing else leaves this crate with no honest way to write the
/// gate. It says so in [`Suggestions::withheld`] rather than inventing one.
#[derive(Clone, Debug, PartialEq)]
pub struct RegimeOutcome {
    pub label: String,
    /// The objective inside this regime. Negative is a loss.
    pub objective: f64,
    /// The share of the window this regime covered.
    pub share_of_window: f64,
    /// The predicate that is true inside this regime, when the caller has one.
    pub gate: Option<Predicate>,
}

/// How often one exit reason closed a trade.
#[derive(Clone, Debug, PartialEq)]
pub struct ExitReasonShare {
    /// `ExitRule::kind()` — `stop_loss`, `take_profit`, `max_holding_bars`, …
    pub reason: String,
    pub share: f64,
    pub trades: u64,
}

/// Everything a run learned that this crate can reason from.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Findings {
    pub blocking: Option<BlockingProfile>,
    pub regimes: Vec<RegimeOutcome>,
    pub exit_reasons: Vec<ExitReasonShare>,
}

// ── the citation ─────────────────────────────────────────────────────────────

/// A measurement, not a sentence.
///
/// Every variant carries the numbers it was read off, so a suggestion's `why`
/// is checkable against the run that produced it. This is the whole of S-5.11's
/// acceptance made structural: there is no `Evidence::Because(String)`.
#[derive(Clone, Debug, PartialEq)]
pub enum Evidence {
    /// One clause emptied the condition.
    SoleBlocker {
        entry: String,
        clause: String,
        true_share: f64,
        sole_blocker_share: f64,
        bars_evaluated: u64,
    },
    /// It never fired and no one clause is to blame.
    NoSingleBlocker {
        entry: String,
        bars_evaluated: u64,
        rarest_clause: String,
        rarest_true_share: f64,
    },
    /// It fired on so many bars that it is not selecting anything.
    FiresTooOften {
        entry: String,
        fire_share: f64,
        bars_evaluated: u64,
    },
    /// It lost money in a regime that covered a real share of the window.
    LosesInRegime {
        label: String,
        objective: f64,
        share_of_window: f64,
    },
    /// One exit reason closed nearly every trade.
    ExitDominates {
        reason: String,
        share: f64,
        trades: u64,
    },
}

impl Evidence {
    /// The measurement, in words, with its numbers.
    #[must_use]
    pub fn words(&self) -> String {
        match self {
            Self::SoleBlocker {
                entry,
                clause,
                true_share,
                sole_blocker_share,
                bars_evaluated,
            } => format!(
                "over {bars_evaluated} bars, `{entry}` never fired: `{clause}` was true on {} \
                 of bars and was the sole blocker on {} of the rest",
                pct(*true_share),
                pct(*sole_blocker_share)
            ),
            Self::NoSingleBlocker {
                entry,
                bars_evaluated,
                rarest_clause,
                rarest_true_share,
            } => format!(
                "over {bars_evaluated} bars, `{entry}` never fired and no clause was the sole \
                 blocker on half the failures; the rarest is `{rarest_clause}`, true on {}",
                pct(*rarest_true_share)
            ),
            Self::FiresTooOften {
                entry,
                fire_share,
                bars_evaluated,
            } => format!(
                "over {bars_evaluated} bars, `{entry}` was true on {} of them — it is not \
                 selecting anything",
                pct(*fire_share)
            ),
            Self::LosesInRegime {
                label,
                objective,
                share_of_window,
            } => format!(
                "the objective inside the `{label}` regime was {objective:.4}, over {} of the \
                 window",
                pct(*share_of_window)
            ),
            Self::ExitDominates {
                reason,
                share,
                trades,
            } => format!("`{reason}` closed {} of {trades} trades", pct(*share)),
        }
    }
}

// ── the suggestion ───────────────────────────────────────────────────────────

/// The edit being proposed. Fragments only — see [`Fragment`].
#[derive(Clone, Debug, PartialEq)]
pub enum Proposal {
    /// Move one number in a clause, in the named direction. No target value:
    /// a blocking profile says a threshold is binding, not what it should be,
    /// and a number chosen here would be a guess wearing a measurement's
    /// authority.
    MoveThreshold {
        clause: Fragment,
        literal: Fragment,
        direction: Direction,
    },
    /// Move the range a swept parameter is drawn from.
    WidenParamRange {
        param: Fragment,
        direction: Direction,
    },
    /// Drop a clause.
    DropClause { clause: Fragment },
    /// `and` a predicate into a condition. The predicate is typed and was
    /// checked against the catalogue; it is still a fragment, not a strategy.
    AddPredicate { predicate: Predicate },
}

/// One proposed move, with the measurement that motivated it.
#[derive(Clone, Debug, PartialEq)]
pub struct Suggestion {
    pub kind: MoveKind,
    /// The clause this would touch: `entry.long[0].clause[1]`, `exit.stop`.
    pub path: String,
    pub proposal: Proposal,
    pub why: Evidence,
    /// What the move is expected to do, stated so that the next run can
    /// contradict it.
    pub expected_effect: String,
}

/// A rule that fired, and the move it would have proposed if the language
/// could carry it.
#[derive(Clone, Debug, PartialEq)]
pub struct Withheld {
    pub kind: MoveKind,
    pub why: Evidence,
    /// What the platform is missing, in the imperative of a refusal.
    pub because: String,
    /// The diagnostic the compiler would have answered with, when there is one.
    pub code: Option<Code>,
}

/// What [`suggest_moves()`] produced, and what it deliberately did not.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Suggestions {
    pub moves: Vec<Suggestion>,
    pub withheld: Vec<Withheld>,
}

impl Suggestions {
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.moves.is_empty() && self.withheld.is_empty()
    }

    /// The suggestions as lines a person reads.
    #[must_use]
    pub fn render(&self) -> String {
        let mut out = Vec::new();
        for m in &self.moves {
            out.push(format!(
                "{} on {}: {} — because {}",
                m.kind,
                m.path,
                describe(&m.proposal),
                m.why.words()
            ));
        }
        for w in &self.withheld {
            out.push(format!(
                "withheld {}: {} — because {}",
                w.kind,
                w.because,
                w.why.words()
            ));
        }
        out.join("\n")
    }
}

fn describe(p: &Proposal) -> String {
    match p {
        Proposal::MoveThreshold {
            clause,
            literal,
            direction,
        } => format!("{} `{literal}` in `{clause}`", direction.as_str()),
        Proposal::WidenParamRange { param, direction } => {
            format!("{} the range of `{param}`", direction.as_str())
        }
        Proposal::DropClause { clause } => format!("drop `{clause}`"),
        Proposal::AddPredicate { predicate } => format!("add `and {}`", predicate.text()),
    }
}

