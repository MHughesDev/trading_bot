/// Propose the next structural moves, against the engine's registry.
///
/// # Errors
///
/// Whatever the definition has that SLv2 has no text for, named by
/// [`crate::decompile()`].
pub fn suggest_moves(
    def: &StrategyDefinition,
    findings: &Findings,
) -> Result<Suggestions, Diagnostic> {
    suggest_moves_with(def, findings, &Catalogue::engine())
}

/// As [`suggest_moves()`], against a caller-supplied catalogue.
///
/// # Errors
///
/// As [`suggest_moves()`].
pub fn suggest_moves_with(
    def: &StrategyDefinition,
    findings: &Findings,
    cat: &Catalogue,
) -> Result<Suggestions, Diagnostic> {
    let entries = crate::block::entry_clauses_with(def, cat)?;
    let mut out = Suggestions::default();

    if let Some(profile) = &findings.blocking {
        for entry in &profile.entries {
            match &entry.verdict {
                Verdict::Blocked {
                    clause,
                    sole_blocker_share,
                } => blocked(entry, *clause, *sole_blocker_share, &mut out),
                Verdict::NoSingleBlocker => no_single_blocker(entry, &mut out),
                Verdict::Fires { share } if *share >= FIRES_TOO_OFTEN => {
                    fires_too_often(entry, *share, &mut out);
                }
                Verdict::Fires { .. } | Verdict::NothingEvaluated => {}
            }
        }
    }

    for regime in &findings.regimes {
        if regime.objective >= 0.0 || regime.share_of_window < REGIME_WORTH_GATING {
            continue;
        }
        let why = Evidence::LosesInRegime {
            label: regime.label.clone(),
            objective: regime.objective,
            share_of_window: regime.share_of_window,
        };
        match &regime.gate {
            Some(gate) => {
                for entry in &entries {
                    out.moves.push(Suggestion {
                        kind: MoveKind::AddRegimeGate,
                        path: format!("{}.when", entry.path),
                        proposal: Proposal::AddPredicate {
                            predicate: gate.clone(),
                        },
                        why: why.clone(),
                        expected_effect: format!(
                            "stands aside inside the `{}` regime, which cost {:.4}; it will \
                             also give up whatever that regime was earning",
                            regime.label, regime.objective
                        ),
                    });
                }
            }
            None => out.withheld.push(Withheld {
                kind: MoveKind::AddRegimeGate,
                why: why.clone(),
                because: format!(
                    "the diagnostic names the regime `{}` and no feature that tests for it. \
                     `features::registry` does not label which families measure a regime, so a \
                     gate written here would be a guess — supply `RegimeOutcome::gate`",
                    regime.label
                ),
                code: None,
            }),
        }
        // FEAT-003 §8.3's other answer to a losing regime is vol-scaled sizing,
        // and the canonical order specification cannot hold it. The rule still
        // fires; the move is refused by name rather than approximated with
        // `risk_per_trade`, which is a different rule (see `skeleton.rs`'s
        // `VOL_TARGET_NOTES`).
        out.withheld.push(Withheld {
            kind: MoveKind::ChangeSizing,
            why,
            because: "`domain::strategy_def::actions::SizeMode` has `fixed`, \
                      `percent_of_balance` and `risk_unit`, and none of them scales a quantity \
                      by a measured volatility"
                .into(),
            code: Some(Code::SizeModeNotRepresentable),
        });
    }

    exits(def, findings, &mut out);
    Ok(out)
}

fn blocked(entry: &EntryProfile, clause: usize, sole_blocker_share: f64, out: &mut Suggestions) {
    let c = &entry.clauses[clause];
    let why = Evidence::SoleBlocker {
        entry: entry.path.clone(),
        clause: c.text.clone(),
        true_share: c.true_share,
        sole_blocker_share,
        bars_evaluated: entry.bars_evaluated,
    };
    let Some(frag) = Fragment::new(c.text.as_str()) else {
        return;
    };
    match movable(&c.text, Loosen::True) {
        Some(Movable::Literal { literal, direction }) => out.moves.push(Suggestion {
            kind: MoveKind::ChangeThreshold,
            path: c.path.clone(),
            proposal: Proposal::MoveThreshold {
                clause: frag,
                literal,
                direction,
            },
            why,
            expected_effect: format!(
                "`{}`ing it makes this clause true on more bars, so the condition can fire",
                direction.as_str()
            ),
        }),
        Some(Movable::Param { param, direction }) => out.moves.push(Suggestion {
            kind: MoveKind::ChangeThreshold,
            path: c.path.clone(),
            proposal: Proposal::WidenParamRange { param, direction },
            why,
            expected_effect:
                "the binding number is swept, so the sweep's range is what has to move, not the \
                 clause"
                    .into(),
        }),
        None => out.moves.push(Suggestion {
            kind: MoveKind::RemoveFilter,
            path: c.path.clone(),
            proposal: Proposal::DropClause { clause: frag },
            why,
            expected_effect:
                "this clause has no threshold to move, and it is what emptied the condition"
                    .into(),
        }),
    }
}

fn no_single_blocker(entry: &EntryProfile, out: &mut Suggestions) {
    let Some(rarest) = entry.clauses.iter().min_by(|a, b| {
        a.true_share
            .partial_cmp(&b.true_share)
            .unwrap_or(std::cmp::Ordering::Equal)
    }) else {
        return;
    };
    let why = Evidence::NoSingleBlocker {
        entry: entry.path.clone(),
        bars_evaluated: entry.bars_evaluated,
        rarest_clause: rarest.text.clone(),
        rarest_true_share: rarest.true_share,
    };
    let Some(frag) = Fragment::new(rarest.text.as_str()) else {
        return;
    };
    out.moves.push(Suggestion {
        kind: MoveKind::RemoveFilter,
        path: rarest.path.clone(),
        proposal: Proposal::DropClause { clause: frag },
        why,
        expected_effect:
            "more than one clause fails at a time, so moving a single threshold will not make \
             it fire; taking the rarest one away is the smallest change that can"
                .into(),
    });
}

fn fires_too_often(entry: &EntryProfile, share: f64, out: &mut Suggestions) {
    let why = Evidence::FiresTooOften {
        entry: entry.path.clone(),
        fire_share: share,
        bars_evaluated: entry.bars_evaluated,
    };
    // The widest clause first, then the next widest: a condition whose widest
    // clause compares two features has nothing to tighten *there*, and stopping
    // at it would withhold a move the condition can perfectly well carry.
    let mut ranked: Vec<&crate::block::ClauseProfile> = entry.clauses.iter().collect();
    ranked.sort_by(|a, b| {
        b.true_share
            .partial_cmp(&a.true_share)
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    let found = ranked.into_iter().find_map(|c| {
        let frag = Fragment::new(c.text.as_str())?;
        match movable(&c.text, Loosen::False)? {
            Movable::Literal { literal, direction } => Some((
                c,
                Proposal::MoveThreshold {
                    clause: frag,
                    literal,
                    direction,
                },
                direction,
            )),
            Movable::Param { param, direction } => Some((
                c,
                Proposal::WidenParamRange { param, direction },
                direction,
            )),
        }
    });
    match found {
        Some((c, proposal, direction)) => out.moves.push(Suggestion {
            kind: MoveKind::ChangeThreshold,
            path: c.path.clone(),
            proposal,
            why,
            expected_effect: format!(
                "`{}`ing it makes the widest clause true on fewer bars, so the condition \
                 selects something",
                direction.as_str()
            ),
        }),
        None => out.withheld.push(Withheld {
            kind: MoveKind::AddFilter,
            why,
            because: "no clause in this condition has a number to tighten, and the measurement \
                      says only that it fires too often — it does not say what to filter on. A \
                      predicate chosen here would be exploration, which AGENT-011 §10 puts in \
                      the Experiment step"
                .into(),
            code: None,
        }),
    }
}

fn exits(def: &StrategyDefinition, findings: &Findings, out: &mut Suggestions) {
    let Some(ExitPolicy::Rules { rules }) = def.exit_policy() else {
        return;
    };
    for seen in &findings.exit_reasons {
        if seen.share < EXIT_REASON_DOMINATES {
            continue;
        }
        let why = Evidence::ExitDominates {
            reason: seen.reason.clone(),
            share: seen.share,
            trades: seen.trades,
        };
        let Some(rule) = rules.iter().find(|r| r.kind() == seen.reason.as_str()) else {
            continue;
        };
        // `exit.stop 0.03` and `exit.trailing 0.03` are SLv2 text, and this
        // grammar has no syntax for a scaled distance yet (Q-S5-01: `atr`/
        // `sigma` are refused by name in the compiler, not merely unwritten in
        // the printer). Suggesting a bare number for an atr- or sigma-scaled
        // rule would silently drop its unit and hand back a fraction-of-entry
        // clause meaning something else entirely — refused rather than
        // guessed, same as the compiler refuses the other direction.
        let (path, literal, effect) = match rule {
            ExitRule::StopLoss { distance } => {
                let Some(fraction) = distance.as_fraction_of_entry() else {
                    continue;
                };
                (
                    "exit.stop",
                    fraction.to_string(),
                    "a stop that closes nearly every trade is being hit by noise rather than by \
                     the hypothesis failing; widening it lets the trade breathe, at a larger loss \
                     per stop-out",
                )
            }
            ExitRule::MaxHoldingBars { bars } => (
                "exit.time",
                bars.to_string(),
                "the holding limit, not the hypothesis, is closing these trades; a longer one \
                 says whether the edge needed more bars",
            ),
            ExitRule::TrailingStop { distance } => {
                let Some(fraction) = distance.as_fraction_of_entry() else {
                    continue;
                };
                (
                    "exit.trailing",
                    fraction.to_string(),
                    "the trailing stop is closing nearly every trade, so it is tracking noise; a \
                     wider one gives the move room",
                )
            }
            ExitRule::TakeProfit { .. } | ExitRule::OnSignal { .. } => continue,
        };
        let Some(literal) = Fragment::new(literal) else {
            continue;
        };
        let Some(clause) = Fragment::new(format!("exit {} {literal}", path.trim_start_matches("exit.")))
        else {
            continue;
        };
        out.moves.push(Suggestion {
            kind: MoveKind::ChangeThreshold,
            path: path.into(),
            proposal: Proposal::MoveThreshold {
                clause,
                literal,
                direction: Direction::Raise,
            },
            why,
            expected_effect: effect.into(),
        });
    }
}

// ── finding the number that binds ────────────────────────────────────────────

/// Which way the clause should be pushed.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Loosen {
    /// Make the clause true more often.
    True,
    /// Make it true less often.
    False,
}

enum Movable {
    Literal {
        literal: Fragment,
        direction: Direction,
    },
    Param {
        param: Fragment,
        direction: Direction,
    },
}

/// The number in a comparison that would have to move, and which way.
///
/// `None` when the clause is not a comparison against a bare number or a swept
/// parameter — an equality, a comparison of two features, a disjunction. There
/// is nothing to move, and saying so is what makes the `remove_filter` branch
/// honest rather than a fallback.
fn movable(text: &str, want: Loosen) -> Option<Movable> {
    let parsed = crate::parse::expr_from_str(text).ok()?;
    let Expr::Binary { op, lhs, rhs, .. } = &parsed else {
        return None;
    };
    // Which side has to grow to make the comparison true more often:
    // in `X < k`, `k`; in `k < X`, `k` has to shrink.
    let bigger_is_truer = match op {
        BinOp::Lt | BinOp::Le => true,
        BinOp::Gt | BinOp::Ge => false,
        _ => return None,
    };
    let (side, right) = match (&**lhs, &**rhs) {
        (_, Expr::Number(_) | Expr::Name { .. }) => (rhs, true),
        (Expr::Number(_) | Expr::Name { .. }, _) => (lhs, false),
        _ => return None,
    };
    // Moving the *left* operand has the opposite effect to moving the right.
    let raise_makes_true = if right {
        bigger_is_truer
    } else {
        !bigger_is_truer
    };
    let direction = match (want, raise_makes_true) {
        (Loosen::True, true) | (Loosen::False, false) => Direction::Raise,
        (Loosen::True, false) | (Loosen::False, true) => Direction::Lower,
    };
    match &**side {
        Expr::Number(n) => Some(Movable::Literal {
            literal: Fragment::new(n.raw.clone())?,
            direction,
        }),
        Expr::Name { name, .. } => Some(Movable::Param {
            param: Fragment::new(name.clone())?,
            direction,
        }),
        _ => None,
    }
}

fn pct(share: f64) -> String {
    format!("{:.1}%", share * 100.0)
}

fn refuse(code: Code, message: impl Into<String>, fix: impl Into<String>) -> Diagnostic {
    Diagnostic::semantic(code, NO_SOURCE, message)
        .with_fix(fix)
        .with_see("guide#features")
}

