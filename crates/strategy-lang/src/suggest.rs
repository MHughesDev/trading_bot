    fn def(src: &str) -> StrategyDefinition {
        let ast = crate::parse(src).unwrap_or_else(|e| panic!("parse: {e:#?}"));
        crate::compile(&ast).unwrap_or_else(|e| panic!("compile: {e:#?}"))
    }

    fn profile(d: &StrategyDefinition, bars: u64, all_true: u64, per: &[(u64, u64)]) -> BlockingProfile {
        let counts = EntryCounts::new(
            "entry.long[0]",
            bars,
            all_true,
            per.iter()
                .enumerate()
                .map(|(i, (t, b))| ClauseCounts {
                    path: format!("entry.long[0].clause[{i}]"),
                    bars_true: *t,
                    bars_sole_blocker: *b,
                })
                .collect(),
        )
        .expect("a possible tally");
        blocking_profile(d, &[counts]).expect("profile")
    }

    #[test]
    fn a_sole_blocker_with_a_threshold_becomes_a_change_threshold_that_cites_it() {
        let d = def(TWO_CLAUSE);
        let f = Findings {
            blocking: Some(profile(&d, 1000, 0, &[(600, 400), (4, 596)])),
            ..Findings::default()
        };
        let s = suggest_moves(&d, &f).expect("suggestions");
        let m = s
            .moves
            .iter()
            .find(|m| m.kind == MoveKind::ChangeThreshold)
            .expect("a threshold move");
        assert_eq!(m.path, "entry.long[0].clause[1]");
        match &m.proposal {
            Proposal::MoveThreshold {
                clause,
                literal,
                direction,
            } => {
                assert_eq!(clause.as_str(), "rsi(close, 14) < 30");
                assert_eq!(literal.as_str(), "30");
                // `rsi < 30` is false too often, so 30 has to go up.
                assert_eq!(*direction, Direction::Raise);
            }
            other => panic!("expected a threshold move, got {other:?}"),
        }
        assert!(m.why.words().contains("sole blocker"), "{}", m.why.words());
        assert!(m.why.words().contains("59.6%"), "{}", m.why.words());
    }

