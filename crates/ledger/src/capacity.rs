//! Capacity is a property of the definition, not the instance
//! (EXTERNAL-REVIEW-2026-09 §3.3, ADR-P6-08).
//!
//! ## The error
//!
//! Gate 4 measures capacity from one run's bars and trade list: ADV,
//! daily volatility, peak daily notional, and a Sharpe-versus-AUM curve. That
//! is the right measurement of the right thing — for one run.
//!
//! A definition binds to many `(account, instrument)` instances, each running
//! independently, and each one's backtest assumed it traded alone. Fifty
//! instances of a definition are not fifty positions. They are **one position at
//! fifty times the size, with correlation 1.0**, competing for the same
//! liquidity at the same moments. Every risk view that counts them separately is
//! reporting diversification that does not exist.
//!
//! ## The rule
//!
//! Capacity is keyed on `(revision_hash, instrument)` and consumed in aggregate.
//! [`Exposure`] cannot be constructed from one instance — [`Exposure::across`]
//! takes the whole set, because a function that accepts a single instance is a
//! function somebody eventually calls in a loop and sums wrong.
//!
//! ## Effective instance count
//!
//! [`Exposure::effective_instances`] is the honest count: instances of the same
//! revision on the same instrument collapse to one. It is deliberately
//! pessimistic — two instances of the *same* revision on *different* instruments
//! are counted separately even though their signals are generated by identical
//! logic and will often fire together. Estimating that correlation needs return
//! series this module does not have, and guessing it low is the failure mode
//! this module exists to prevent.

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// One live binding of a definition revision to an account and instrument.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Instance {
    /// Content address of the definition this instance is running.
    ///
    /// Not `strategy_id`: a name is a pointer, and two instances pointing at a
    /// name that was re-saved in between are running different programs. This
    /// is why migration 0058 put `revision_hash` on `strategy_instances`.
    pub revision_hash: String,
    pub account_id: String,
    pub instrument_id: String,
    /// Current absolute position notional in USD.
    pub notional_usd: f64,
}

/// Aggregate live exposure of one definition revision.
///
/// No public fields and no single-instance constructor: see the module docs.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[non_exhaustive]
pub struct Exposure {
    revision_hash: String,
    total_notional_usd: f64,
    by_instrument: BTreeMap<String, f64>,
    instance_count: usize,
    effective_instances: usize,
}

impl Exposure {
    /// Aggregate every live instance of `revision_hash`.
    ///
    /// Instances of other revisions are ignored rather than rejected: the caller
    /// usually holds the whole instance table, and making it pre-filter is how a
    /// filter goes wrong silently.
    ///
    /// `None` when no instance of that revision is live — which is a different
    /// answer from zero exposure and is why it is not `Exposure::default()`.
    #[must_use]
    pub fn across(revision_hash: &str, instances: &[Instance]) -> Option<Self> {
        let mine: Vec<&Instance> = instances
            .iter()
            .filter(|i| i.revision_hash == revision_hash)
            .collect();
        if mine.is_empty() {
            return None;
        }

        let mut by_instrument: BTreeMap<String, f64> = BTreeMap::new();
        for i in &mine {
            *by_instrument.entry(i.instrument_id.clone()).or_insert(0.0) += i.notional_usd.abs();
        }

        Some(Self {
            revision_hash: revision_hash.to_string(),
            total_notional_usd: mine.iter().map(|i| i.notional_usd.abs()).sum(),
            effective_instances: by_instrument.len(),
            by_instrument,
            instance_count: mine.len(),
        })
    }

    #[must_use]
    pub fn revision_hash(&self) -> &str {
        &self.revision_hash
    }

    /// Summed absolute notional across every instance.
    #[must_use]
    pub const fn total_notional_usd(&self) -> f64 {
        self.total_notional_usd
    }

    /// Notional on one instrument, summed across every account running this
    /// revision. The number that competes for one book's liquidity.
    #[must_use]
    pub fn on_instrument(&self, instrument_id: &str) -> f64 {
        self.by_instrument.get(instrument_id).copied().unwrap_or(0.0)
    }

    /// How many bindings exist.
    #[must_use]
    pub const fn instance_count(&self) -> usize {
        self.instance_count
    }

    /// How many *independent* positions these amount to, pessimistically: one
    /// per instrument, whatever the account count.
    #[must_use]
    pub const fn effective_instances(&self) -> usize {
        self.effective_instances
    }

    /// The diversification a naive count claims and this revision does not have.
    ///
    /// `instance_count − effective_instances`. A risk view showing thirty
    /// positions where there are three is overstating by twenty-seven.
    #[must_use]
    pub const fn phantom_diversification(&self) -> usize {
        self.instance_count - self.effective_instances
    }

    /// Instruments carrying exposure, largest first.
    #[must_use]
    pub fn concentrations(&self) -> Vec<(&str, f64)> {
        let mut v: Vec<(&str, f64)> = self
            .by_instrument
            .iter()
            .map(|(k, v)| (k.as_str(), *v))
            .collect();
        v.sort_by(|a, b| b.1.total_cmp(&a.1));
        v
    }
}

/// A capacity ceiling for one revision on one instrument, in USD.
///
/// Comes from Gate 4's `sharpe_by_aum` curve — the AUM at which the measured
/// Sharpe falls below the threshold the profile requires. It is an estimate from
/// a model of impact, and [`Ceiling::single_venue`] records when the ADV behind
/// it came from one venue, which *understates* real liquidity and so makes the
/// ceiling conservative rather than wrong.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Ceiling {
    pub instrument_id: String,
    pub ceiling_usd: f64,
    /// Whether the ADV behind this came from a single venue.
    pub single_venue: bool,
    /// The Gate 4 verdict this was read from, for the audit trail.
    pub source_trial_id: String,
}

/// What the aggregate check decided.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(tag = "verdict", rename_all = "snake_case")]
pub enum Admission {
    /// Room for the requested size.
    Admitted { headroom_usd: f64 },
    /// The requested size would put aggregate exposure over the ceiling.
    Refused { reason: String },
    /// No ceiling has been measured for this revision on this instrument.
    ///
    /// **Refuses, and says why.** An unmeasured ceiling is not an infinite one,
    /// and defaulting it to "allowed" is how the platform would grow into a
    /// crowd it never measured.
    Unmeasured { reason: String },
}

impl Admission {
    #[must_use]
    pub const fn is_admitted(&self) -> bool {
        matches!(self, Self::Admitted { .. })
    }
}

/// May this revision add `additional_usd` of exposure on `instrument_id`?
///
/// The check is against **aggregate** exposure, which is why it takes an
/// [`Exposure`] rather than a position: the question "may this instance grow"
/// has no answer that does not involve every other instance of the same
/// revision.
///
/// `exposure` may be `None` when nothing is live yet — the first instance still
/// has to fit under the ceiling on its own.
#[must_use]
pub fn admit(
    exposure: Option<&Exposure>,
    instrument_id: &str,
    additional_usd: f64,
    ceiling: Option<&Ceiling>,
) -> Admission {
    let current = exposure.map_or(0.0, |e| e.on_instrument(instrument_id));
    let proposed = current + additional_usd.abs();

    let Some(c) = ceiling else {
        return Admission::Unmeasured {
            reason: format!(
                "no capacity ceiling has been measured for this revision on {instrument_id}; \
                 aggregate exposure across {} live instance(s) is ${current:.0} and adding \
                 ${:.0} would make it ${proposed:.0}. An unmeasured ceiling is not an infinite \
                 one — run Gate 4's size ladder for this instrument.",
                exposure.map_or(0, Exposure::instance_count),
                additional_usd.abs(),
            ),
        };
    };

    if c.instrument_id != instrument_id {
        return Admission::Unmeasured {
            reason: format!(
                "the supplied ceiling is for {} and the request is for {instrument_id}; capacity \
                 does not transfer between instruments",
                c.instrument_id
            ),
        };
    }

    if proposed > c.ceiling_usd {
        let venue_note = if c.single_venue {
            " (ceiling derived from single-venue ADV, which understates real liquidity)"
        } else {
            ""
        };
        return Admission::Refused {
            reason: format!(
                "aggregate exposure to this revision on {instrument_id} would reach ${proposed:.0} \
                 against a measured ceiling of ${:.0}{venue_note}. {} instance(s) are already \
                 live holding ${current:.0} between them — they are one position at that size \
                 with correlation 1.0, not {} independent ones.",
                c.ceiling_usd,
                exposure.map_or(0, Exposure::instance_count),
                exposure.map_or(0, Exposure::instance_count),
            ),
        };
    }

    Admission::Admitted { headroom_usd: c.ceiling_usd - proposed }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn inst(rev: &str, account: &str, instrument: &str, notional: f64) -> Instance {
        Instance {
            revision_hash: rev.into(),
            account_id: account.into(),
            instrument_id: instrument.into(),
            notional_usd: notional,
        }
    }

    fn ceiling(instrument: &str, usd: f64) -> Ceiling {
        Ceiling {
            instrument_id: instrument.into(),
            ceiling_usd: usd,
            single_venue: false,
            source_trial_id: "trial_1".into(),
        }
    }

    // ── aggregation ──────────────────────────────────────────────────────────

    /// The headline case from the review: fifty accounts running one definition.
    #[test]
    fn fifty_instances_of_one_definition_are_one_position_at_fifty_times_the_size() {
        let instances: Vec<Instance> = (0..50)
            .map(|i| inst("rev_a", &format!("acct_{i}"), "BTC-USD", 10_000.0))
            .collect();
        let e = Exposure::across("rev_a", &instances).unwrap();

        assert_eq!(e.instance_count(), 50);
        assert_eq!(e.effective_instances(), 1, "one instrument, one position");
        assert_eq!(e.phantom_diversification(), 49);
        assert!((e.total_notional_usd() - 500_000.0).abs() < 1e-6);
        assert!((e.on_instrument("BTC-USD") - 500_000.0).abs() < 1e-6);
    }

    #[test]
    fn other_revisions_are_not_counted() {
        let instances = vec![
            inst("rev_a", "a1", "BTC-USD", 100.0),
            inst("rev_b", "a2", "BTC-USD", 900.0),
        ];
        let e = Exposure::across("rev_a", &instances).unwrap();
        assert!((e.total_notional_usd() - 100.0).abs() < 1e-9);
        assert_eq!(e.instance_count(), 1);
    }

    /// A short is exposure too. Summing signed notional would net a long and a
    /// short against each other and report a crowded book as empty.
    #[test]
    fn shorts_count_toward_exposure_rather_than_netting_against_longs() {
        let instances = vec![
            inst("rev_a", "a1", "BTC-USD", 1_000.0),
            inst("rev_a", "a2", "BTC-USD", -1_000.0),
        ];
        let e = Exposure::across("rev_a", &instances).unwrap();
        assert!((e.total_notional_usd() - 2_000.0).abs() < 1e-9);
    }

    #[test]
    fn instruments_are_counted_separately_and_ranked_by_size() {
        let instances = vec![
            inst("rev_a", "a1", "BTC-USD", 100.0),
            inst("rev_a", "a2", "ETH-USD", 500.0),
            inst("rev_a", "a3", "ETH-USD", 200.0),
        ];
        let e = Exposure::across("rev_a", &instances).unwrap();
        assert_eq!(e.effective_instances(), 2);
        assert_eq!(e.concentrations(), vec![("ETH-USD", 700.0), ("BTC-USD", 100.0)]);
    }

    /// "Nothing is live" and "zero exposure" are different answers.
    #[test]
    fn no_live_instances_is_none_rather_than_zero() {
        assert!(Exposure::across("rev_a", &[]).is_none());
        assert!(Exposure::across("rev_a", &[inst("rev_b", "a", "BTC-USD", 1.0)]).is_none());
    }

    // ── admission ────────────────────────────────────────────────────────────

    #[test]
    fn a_request_that_fits_under_the_aggregate_ceiling_is_admitted() {
        let instances = vec![inst("rev_a", "a1", "BTC-USD", 100_000.0)];
        let e = Exposure::across("rev_a", &instances).unwrap();
        match admit(Some(&e), "BTC-USD", 50_000.0, Some(&ceiling("BTC-USD", 1_000_000.0))) {
            Admission::Admitted { headroom_usd } => {
                assert!((headroom_usd - 850_000.0).abs() < 1e-6);
            }
            other => panic!("{other:?}"),
        }
    }

    /// The defect: each instance fits on its own, and together they do not.
    #[test]
    fn each_instance_fits_alone_and_the_aggregate_does_not() {
        let c = ceiling("BTC-USD", 1_000_000.0);

        // One instance asking for 200k, with nothing live: fine.
        assert!(admit(None, "BTC-USD", 200_000.0, Some(&c)).is_admitted());

        // Nine already live at 200k each, and the tenth asks for the same.
        let instances: Vec<Instance> = (0..9)
            .map(|i| inst("rev_a", &format!("a{i}"), "BTC-USD", 200_000.0))
            .collect();
        let e = Exposure::across("rev_a", &instances).unwrap();
        match admit(Some(&e), "BTC-USD", 200_000.0, Some(&c)) {
            Admission::Refused { reason } => {
                assert!(reason.contains("correlation 1.0"), "{reason}");
                assert!(reason.contains("2000000"), "{reason}");
            }
            other => panic!("the tenth instance must be refused, got {other:?}"),
        }
    }

    /// An unmeasured ceiling refuses. Defaulting it to "allowed" is how the
    /// platform grows into a crowd it never measured.
    #[test]
    fn an_unmeasured_ceiling_refuses_and_says_what_to_run() {
        let e = Exposure::across("rev_a", &[inst("rev_a", "a", "BTC-USD", 1.0)]).unwrap();
        match admit(Some(&e), "BTC-USD", 1.0, None) {
            Admission::Unmeasured { reason } => {
                assert!(reason.contains("not an infinite one"), "{reason}");
                assert!(reason.contains("Gate 4"), "{reason}");
            }
            other => panic!("{other:?}"),
        }
        assert!(!admit(None, "BTC-USD", 1.0, None).is_admitted());
    }

    /// Capacity in ETH says nothing about capacity in BTC.
    #[test]
    fn a_ceiling_for_another_instrument_does_not_admit() {
        match admit(None, "BTC-USD", 1.0, Some(&ceiling("ETH-USD", 1e12))) {
            Admission::Unmeasured { reason } => {
                assert!(reason.contains("does not transfer between instruments"), "{reason}");
            }
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn a_single_venue_ceiling_says_so_in_the_refusal() {
        let c = Ceiling { single_venue: true, ..ceiling("BTC-USD", 100.0) };
        match admit(None, "BTC-USD", 1_000.0, Some(&c)) {
            Admission::Refused { reason } => assert!(reason.contains("single-venue ADV"), "{reason}"),
            other => panic!("{other:?}"),
        }
    }

    /// Exposure on a different instrument must not consume this one's ceiling.
    #[test]
    fn the_check_is_per_instrument_not_per_revision_total() {
        let instances = vec![inst("rev_a", "a1", "ETH-USD", 10_000_000.0)];
        let e = Exposure::across("rev_a", &instances).unwrap();
        assert!(admit(Some(&e), "BTC-USD", 1_000.0, Some(&ceiling("BTC-USD", 5_000.0))).is_admitted());
    }

    #[test]
    fn a_reduction_request_is_measured_by_its_magnitude() {
        // Size requests arrive signed; capacity is about how much book you are
        // taking, not which way you are facing.
        let e = Exposure::across("rev_a", &[inst("rev_a", "a", "BTC-USD", 90.0)]).unwrap();
        let c = ceiling("BTC-USD", 100.0);
        assert!(admit(Some(&e), "BTC-USD", -5.0, Some(&c)).is_admitted());
        assert!(!admit(Some(&e), "BTC-USD", -50.0, Some(&c)).is_admitted());
    }

    #[test]
    fn exposure_round_trips_through_json() {
        let e = Exposure::across("rev_a", &[inst("rev_a", "a", "BTC-USD", 1.0)]).unwrap();
        let s = serde_json::to_string(&e).unwrap();
        assert_eq!(serde_json::from_str::<Exposure>(&s).unwrap(), e);
    }
}
