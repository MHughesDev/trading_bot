//! Make the templates directory visible to the catalogue (Set S task S-3.1).
//!
//! `apps/skill-runner/templates/<ns>/<name>.py` is the declaration of a tool. The
//! catalogue is built at run time from those headers, and this script exists for
//! one reason: `include_str!` needs a literal path, so something has to write the
//! list of literals. It emits
//!
//! ```ignore
//! pub static TEMPLATE_FILES: &[(&str, &str)] = &[("analysis/x.py", include_str!("..."))];
//! ```
//!
//! and nothing else. In particular it does **not** parse the headers: parsing
//! lives in `skills::template` so that the catalogue and the runner cannot read
//! one file two ways, and pulling that crate in as a build-dependency would
//! compile tokio for the host on every build of this one.
//!
//! Embedding the sources rather than reading the directory at run time is what
//! makes a deployed binary self-contained. A server that read templates from disk
//! would offer a different catalogue depending on what was mounted next to it,
//! and "which tools exist" would stop being a property of the build.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets this"));
    let root = manifest
        .parent()
        .and_then(Path::parent)
        .expect("crates/<name> is two levels below the workspace root")
        .to_path_buf();
    let templates = root.join("apps").join("skill-runner").join("templates");

    println!("cargo:rerun-if-changed={}", templates.display());
    println!(
        "cargo:rerun-if-changed={}",
        root.join("apps")
            .join("skill-runner")
            .join("preamble.py")
            .display()
    );

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    if templates.is_dir() {
        let mut namespaces: Vec<PathBuf> = std::fs::read_dir(&templates)
            .expect("the templates directory is readable")
            .filter_map(Result::ok)
            .map(|e| e.path())
            .filter(|p| p.is_dir())
            .collect();
        namespaces.sort();
        for ns_dir in namespaces {
            println!("cargo:rerun-if-changed={}", ns_dir.display());
            let ns = ns_dir
                .file_name()
                .and_then(|s| s.to_str())
                .expect("a namespace directory has a UTF-8 name")
                .to_string();
            let mut entries: Vec<PathBuf> = std::fs::read_dir(&ns_dir)
                .expect("a namespace directory is readable")
                .filter_map(Result::ok)
                .map(|e| e.path())
                .filter(|p| p.extension().and_then(|e| e.to_str()) == Some("py"))
                .collect();
            // Sorted, so the catalogue's order is the same on every machine:
            // `read_dir` order is the filesystem's, and a catalogue whose order
            // depends on the filesystem is a catalogue whose *diff* does.
            entries.sort();
            for path in entries {
                let name = path
                    .file_name()
                    .and_then(|s| s.to_str())
                    .expect("a template has a UTF-8 name")
                    .to_string();
                files.push((format!("{ns}/{name}"), path));
            }
        }
    }

    let mut out = String::new();
    out.push_str(
        "// Generated by build.rs. Every .py under apps/skill-runner/templates, in\n\
         // (namespace, name) order, with its source embedded.\n\
         pub static TEMPLATE_FILES: &[(&str, &str)] = &[\n",
    );
    for (rel, path) in &files {
        // A path with a quote or a backslash in it would break the literal. On
        // Windows every path has backslashes, so the literal is a raw string with
        // a hash guard, and a path containing `"#` is refused rather than emitted
        // as something that happens to compile.
        let display = path.display().to_string();
        assert!(
            !display.contains("\"#"),
            "template path {display} cannot be embedded; rename it"
        );
        let _ = writeln!(out, "    ({rel:?}, include_str!(r#\"{display}\"#)),");
    }
    out.push_str("];\n");

    let dest =
        PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets this")).join("templates.rs");
    std::fs::write(&dest, out).expect("the generated template list is writable");
}
