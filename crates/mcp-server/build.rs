//! Reads the templated-tool directory into the catalogue at build time.
//!
//! AGENT-006 §2.2, §3.3; Set S tasks S-3.1, S-3.2.
//!
//! A templated tool is a Python file under
//! `apps/skill-runner/templates/<namespace>/<name>.py` whose module docstring
//! carries a fenced JSON `ToolSpec` header. This script finds those files,
//! extracts the headers, and emits them into `$OUT_DIR/templates.rs` for
//! `tools/templated.rs` to turn into `ToolSpec`s.
//!
//! **Why the header is the only declaration.** The obvious design is a header in
//! the Python and a matching `ToolSpec` in Rust, kept in agreement by a test.
//! That is the shape `taxonomy.rs` had before Set S task S-1.3 and it is the
//! shape that produced `promote_model` vs `promote_model_version` — two copies
//! that can disagree eventually do. So there is one copy: the header, and the
//! catalogue entry is generated from it. The templated tier cannot drift from the
//! catalogue because there is nothing for it to drift from.
//!
//! **What this script refuses.** Three checks fail the *build*, not a test,
//! because each describes a template that must never be installed at all:
//!
//! - a file with no JSON header — an undeclared tool is an unclassified tool;
//! - an import of `socket`, `requests`, `subprocess`, `urllib`, `http.client`,
//!   `ftplib` or `smtplib` — a skill has no network and no database (the runner
//!   enforces this at run time too, and a template that tries is a defect worth
//!   catching before it ships);
//! - a name or namespace that disagrees with the file's own path — a tool whose
//!   header says `analysis` in a `audit/` directory is in two namespaces.
//!
//! Everything else — schema agreement with the template body, per-namespace time
//! limits, seed and provenance — is asserted in `templated.rs`'s tests, where a
//! real JSON parser is available. This script deliberately does no JSON parsing:
//! adding `serde_json` as a build-dependency would be a second dependency graph
//! compiled for every build of this crate, and plain string checks cover the
//! three things that must fail hard.

use std::fs;
use std::path::{Path, PathBuf};

/// Imports that mean the template is trying to reach outside the sandbox.
const FORBIDDEN_IMPORTS: &[&str] = &[
    "socket",
    "requests",
    "subprocess",
    "urllib",
    "http.client",
    "httpx",
    "ftplib",
    "smtplib",
    "sqlite3",
    "psycopg",
    "asyncpg",
];

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let root = manifest
        .parent()
        .and_then(Path::parent)
        .expect("crates/mcp-server has a workspace root two levels up");
    let templates = root.join("apps").join("skill-runner").join("templates");

    println!("cargo:rerun-if-changed={}", templates.display());

    let mut entries: Vec<(String, String, String)> = Vec::new();
    if templates.is_dir() {
        for ns_dir in read_sorted(&templates) {
            if !ns_dir.is_dir() {
                continue;
            }
            let namespace = file_stem(&ns_dir);
            println!("cargo:rerun-if-changed={}", ns_dir.display());
            for file in read_sorted(&ns_dir) {
                if file.extension().and_then(|e| e.to_str()) != Some("py") {
                    continue;
                }
                println!("cargo:rerun-if-changed={}", file.display());
                let source = fs::read_to_string(&file)
                    .unwrap_or_else(|e| panic!("template {}: {e}", file.display()));
                let name = file_stem(&file);
                let rel = format!("{namespace}/{name}.py");

                let header = extract_header(&source).unwrap_or_else(|| {
                    panic!(
                        "template {rel} has no ```json header in its module docstring; \
                         an undeclared tool is an unclassified tool"
                    )
                });
                check_identity(&rel, &header, &name, &namespace);
                check_no_network(&rel, &source);

                entries.push((rel, header, source));
            }
        }
    }

    let mut out = String::from(
        "// @generated by crates/mcp-server/build.rs — do not edit.\n\
         /// `(relative path, header JSON, source)` for every installed template.\n\
         pub static TEMPLATE_FILES: &[(&str, &str, &str)] = &[\n",
    );
    for (rel, header, source) in &entries {
        out.push_str(&format!(
            "    ({}, {}, {}),\n",
            raw_str(rel),
            raw_str(header),
            raw_str(source)
        ));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("templates.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("writing {}: {e}", dest.display()));
}

fn read_sorted(dir: &Path) -> Vec<PathBuf> {
    let mut paths: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("reading {}: {e}", dir.display()))
        .filter_map(Result::ok)
        .map(|e| e.path())
        .collect();
    // Sorted so the generated catalogue order is the same on every machine; an
    // order that depends on the filesystem makes a tool's position in the
    // exposure list non-reproducible.
    paths.sort();
    paths
}

fn file_stem(p: &Path) -> String {
    p.file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or_default()
        .to_string()
}

/// The first ```json … ``` block in the file, which by convention is inside the
/// module docstring.
fn extract_header(source: &str) -> Option<String> {
    let start = source.find("```json")? + "```json".len();
    let rest = &source[start..];
    let end = rest.find("```")?;
    Some(rest[..end].trim().to_string())
}

fn check_identity(rel: &str, header: &str, name: &str, namespace: &str) {
    for (field, expected) in [("name", name), ("namespace", namespace)] {
        let needle = format!("\"{field}\"");
        let Some(at) = header.find(&needle) else {
            panic!("template {rel}: header has no `{field}`");
        };
        let after = &header[at + needle.len()..];
        let value: String = after
            .trim_start()
            .strip_prefix(':')
            .unwrap_or(after)
            .trim_start()
            .strip_prefix('"')
            .unwrap_or_default()
            .chars()
            .take_while(|c| *c != '"')
            .collect();
        assert!(
            value == expected,
            "template {rel}: header says {field} `{value}` but the file path says \
             `{expected}` — a tool in two namespaces routes to neither"
        );
    }
}

fn check_no_network(rel: &str, source: &str) {
    for line in source.lines() {
        let t = line.trim();
        // Only real import statements; the words appear in prose and in the
        // refusal messages templates print.
        let module = if let Some(m) = t.strip_prefix("import ") {
            m
        } else if let Some(m) = t.strip_prefix("from ") {
            m.split_whitespace().next().unwrap_or("")
        } else {
            continue;
        };
        let head = module
            .split(|c: char| c == ' ' || c == ',' || c == '.')
            .next()
            .unwrap_or("");
        let dotted = module.split_whitespace().next().unwrap_or("");
        for bad in FORBIDDEN_IMPORTS {
            if head == *bad || dotted == *bad {
                panic!(
                    "template {rel} imports `{bad}`: a skill has no network and no \
                     database, and the data it analyses arrives as a parquet file at \
                     payload[\"data_path\"]"
                );
            }
        }
    }
}

/// A Rust raw string with enough hashes to contain `s` whatever it holds.
fn raw_str(s: &str) -> String {
    let mut hashes = 1;
    while s.contains(&format!("\"{}", "#".repeat(hashes))) {
        hashes += 1;
    }
    let h = "#".repeat(hashes);
    format!("r{h}\"{s}\"{h}")
}
